/**
 * Returns available fast moves and charged moves suggestions for any Pokemon based on its name and types.
 */
export function getMovesetSuggestions(name: string, types: PokemonType[]): {
  fastMoves: string[];
  chargedMoves: string[];
  recommendedRaid?: { fast: string; charged: string[] };
  recommendedPvp?: { fast: string; charged: string[] };
} {
  const cleanName = (name || '').trim();
  const custom = POPULAR_POKEMON_MOVESETS[cleanName];
  if (custom) {
    return {
      fastMoves: custom.fastMoves,
      chargedMoves: custom.chargedMoves,
      recommendedRaid: custom.recommendedRaidSet,
      recommendedPvp: custom.recommendedPvpSet,
    };
  }

  // Fallback: Aggregate moves from primary and secondary types, plus Normal fallback moves
  const fastSet = new Set<string>();
  const chargedSet = new Set<string>();

  const targetTypes = types && types.length > 0 ? types : (['Normal'] as PokemonType[]);

  targetTypes.forEach((t) => {
    (TYPE_FAST_MOVES[t] || []).forEach((m) => fastSet.add(m));
    (TYPE_CHARGED_MOVES[t] || []).forEach((m) => chargedSet.add(m));
  });

  // Always include common general moves if list is small
  if (fastSet.size < 3) {
    ['Tackle', 'Quick Attack', 'Scratch'].forEach((m) => fastSet.add(m));
  }
  if (chargedSet.size < 3) {
    ['Body Slam', 'Hyper Beam', 'Return'].forEach((m) => chargedSet.add(m));
  }

  const fastList = Array.from(fastSet);
  const chargedList = Array.from(chargedSet);

  return {
    fastMoves: fastList,
    chargedMoves: chargedList,
    recommendedRaid: {
      fast: fastList[0] || 'Tackle',
      charged: [chargedList[0] || 'Hyper Beam', chargedList[1] || 'Body Slam'].filter(Boolean),
    },
    recommendedPvp: {
      fast: fastList[0] || 'Tackle',
      charged: [chargedList[0] || 'Body Slam', chargedList[1] || 'Hyper Beam'].filter(Boolean),
    },
  };
}
