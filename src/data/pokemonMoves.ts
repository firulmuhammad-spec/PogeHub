/**
 * Returns the elemental type for any given Pokémon GO move name
 */
export function getMoveType(moveName: string): PokemonType {
  if (!moveName) return 'Normal';
  const clean = moveName.trim();
  if (MOVE_TYPE_MAP[clean]) {
    return MOVE_TYPE_MAP[clean];
  }

  // Heuristic fallbacks based on common words in move names
  const lower = clean.toLowerCase();
  if (lower.includes('fire') || lower.includes('flame') || lower.includes('ember') || lower.includes('burn') || lower.includes('heat') || lower.includes('blast burn')) return 'Fire';
  if (lower.includes('water') || lower.includes('hydro') || lower.includes('aqua') || lower.includes('surf') || lower.includes('bubble') || lower.includes('scald')) return 'Water';
  if (lower.includes('grass') || lower.includes('leaf') || lower.includes('vine') || lower.includes('seed') || lower.includes('petal') || lower.includes('solar')) return 'Grass';
  if (lower.includes('thunder') || lower.includes('volt') || lower.includes('spark') || lower.includes('shock') || lower.includes('charge') || lower.includes('zap')) return 'Electric';
  if (lower.includes('ice') || lower.includes('frost') || lower.includes('blizzard') || lower.includes('snow') || lower.includes('freeze') || lower.includes('avalanche') || lower.includes('glaci')) return 'Ice';
  if (lower.includes('punch') || lower.includes('chop') || lower.includes('kick') || lower.includes('combat') || lower.includes('force') || lower.includes('aura') || lower.includes('strike')) return 'Fighting';
  if (lower.includes('poison') || lower.includes('sludge') || lower.includes('acid') || lower.includes('gunk') || lower.includes('toxic') || lower.includes('venom')) return 'Poison';
  if (lower.includes('earth') || lower.includes('mud') || lower.includes('sand') || lower.includes('drill') || lower.includes('ground') || lower.includes('quake')) return 'Ground';
  if (lower.includes('wing') || lower.includes('air') || lower.includes('fly') || lower.includes('gust') || lower.includes('brave bird') || lower.includes('peck') || lower.includes('sky')) return 'Flying';
  if (lower.includes('psych') || lower.includes('psy') || lower.includes('mind') || lower.includes('zen') || lower.includes('future') || lower.includes('confusion')) return 'Psychic';
  if (lower.includes('bug') || lower.includes('fury cutter') || lower.includes('scissor') || lower.includes('buzz') || lower.includes('sting') || lower.includes('megahorn')) return 'Bug';
  if (lower.includes('rock') || lower.includes('stone') || lower.includes('gem') || lower.includes('meteor') || lower.includes('ancient power') || lower.includes('smack down')) return 'Rock';
  if (lower.includes('shadow') || lower.includes('ghost') || lower.includes('lick') || lower.includes('hex') || lower.includes('poltergeist') || lower.includes('astonish')) return 'Ghost';
  if (lower.includes('dragon') || lower.includes('draco') || lower.includes('outrage') || lower.includes('spacial') || lower.includes('roar of time')) return 'Dragon';
  if (lower.includes('dark') || lower.includes('bite') || lower.includes('crunch') || lower.includes('snarl') || lower.includes('foul') || lower.includes('night slash') || lower.includes('brutal')) return 'Dark';
  if (lower.includes('steel') || lower.includes('metal') || lower.includes('iron') || lower.includes('magnet') || lower.includes('heavy slam') || lower.includes('flash cannon') || lower.includes('bullet punch')) return 'Steel';
  if (lower.includes('fairy') || lower.includes('charm') || lower.includes('dazzling') || lower.includes('moon') || lower.includes('play rough') || lower.includes('kiss')) return 'Fairy';

  return 'Normal';
}

